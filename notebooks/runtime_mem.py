# %% [markdown]
# # Runtime, peak GPU memory and throughput of the SpecShade-256 detector (GPU, ~3 min)
# DDIM inversion in batches of 8, then the sequential rotation + crop searches with the flip candidate (final256.yaml), and the
# joint search of the compound mode (final256_combo.yaml) on the same images. Writes $TAB_OUT/numbers_runtime.tex.
# Usage (GPU node): TAB_OUT=/path/to/paper/tables python notebooks/runtime_mem.py

# %%
import json
import os
import sys
import time
from pathlib import Path

import torch
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from core.sd_backend import SDBackend  # noqa: E402
from models import build_method  # noqa: E402
from utils.io import load_config, read_jsonl  # noqa: E402

OUT = Path(os.environ.get("TAB_OUT", ROOT.parent / "docs" / "manuscripts" / "tables"))
N, B = 32, 8
gen = read_jsonl(ROOT / "results/final256/stylering/gen.jsonl")[:N]
ims = [Image.open(ROOT / g["image"]).convert("RGB") for g in gen]
cfg = load_config(ROOT / "configs/final256.yaml")
be = SDBackend(model_id=cfg["backend"]["model_id"], prefer_fp16=cfg["backend"]["prefer_fp16"], size=cfg["backend"]["size"])
method = build_method("stylering", cfg, be)
torch.cuda.reset_peak_memory_stats(); torch.cuda.synchronize()
mem_model = torch.cuda.memory_allocated() / 1e9
be.invert_batch(ims[:B], steps=50)                     # warm-up
torch.cuda.synchronize(); torch.cuda.reset_peak_memory_stats(); t0 = time.time()
Z = torch.cat([be.invert_batch(ims[i:i + B], steps=50).cpu() for i in range(0, N, B)])
torch.cuda.synchronize(); t_inv = (time.time() - t0) / N; mem_inv = torch.cuda.max_memory_allocated() / 1e9
torch.cuda.reset_peak_memory_stats(); t0 = time.time()
for z in Z:
    method.extract(z.unsqueeze(0))
t_seq = (time.time() - t0) / N; mem_seq = torch.cuda.max_memory_allocated() / 1e9
cfg_c = load_config(ROOT / "configs/final256_combo.yaml")
mc = build_method("stylering", cfg_c, be)
mc.geo_search, mc.geo_fallback = True, False       # force the joint search on every image
torch.cuda.reset_peak_memory_stats(); t0 = time.time()
for z in Z[:8]:
    mc.extract(z.unsqueeze(0))
t_joint = (time.time() - t0) / 8; mem_joint = torch.cuda.max_memory_allocated() / 1e9
r = {"t_inv_s": t_inv, "t_sync_s": t_seq, "t_joint_s": t_joint, "mem_model_gb": mem_model, "mem_inv_gb": mem_inv, "mem_sync_gb": mem_seq,
     "mem_joint_gb": mem_joint, "throughput_img_per_s": 1.0 / (t_inv + t_seq), "gpu": torch.cuda.get_device_name(0)}
print(json.dumps(r, indent=1))
(ROOT / "results/runtime_mem.json").write_text(json.dumps(r, indent=1))
lines = ["% generated by code/notebooks/runtime_mem.py -- do not edit",
         f"\\newcommand{{\\nRtInv}}{{{t_inv:.2f}}}", f"\\newcommand{{\\nRtSync}}{{{t_seq:.2f}}}", f"\\newcommand{{\\nRtJoint}}{{{t_joint:.1f}}}",
         f"\\newcommand{{\\nRtMemInv}}{{{mem_inv:.1f}}}", f"\\newcommand{{\\nRtMemSync}}{{{mem_seq:.1f}}}", f"\\newcommand{{\\nRtMemJoint}}{{{mem_joint:.1f}}}",
         f"\\newcommand{{\\nRtThroughput}}{{{1.0 / (t_inv + t_seq):.2f}}}", f"\\newcommand{{\\nRtPerHour}}{{{3600.0 / (t_inv + t_seq):,.0f}}}"]
(OUT / "numbers_runtime.tex").write_text("\n".join(lines) + "\n")
