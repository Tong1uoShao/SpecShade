import json
import os
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
OUT = Path(os.environ.get("TAB_OUT", ROOT.parent / "docs" / "manuscripts" / "tables"))
OUT.mkdir(parents=True, exist_ok=True)

KEYS = [("Regen.\\ $\\times1$", ["regen_sd@1.0", "regen_sd@1"]), ("Regen.\\ $\\times2$", ["regen_sd@2.0", "regen_sd@2"]),
        ("Regen.\\ $\\times4$", ["regen_sd@4.0", "regen_sd@4"]), ("VAE-Cheng", ["vae_cheng@3.0", "vae_cheng@3"]),
        ("img2img $s{=}0.3$", ["img2img_anime@0.3"]), ("img2img $s{=}0.5$", ["img2img_anime@0.5"]),
        ("AdaIN $\\alpha{=}0.6$", ["adain_anime@0.6"]), ("AdaIN $\\alpha{=}1.0$", ["adain_anime@1.0"]), ("IP2P $g_I{=}1.0$", ["ip2p_anime@1.0"]),
        ("JPEG $Q{=}25$", ["jpeg@25.0", "jpeg@25"]), ("Blur $r{=}8$", ["blur@8.0", "blur@8"]), ("Crop $a{=}0.75$", ["crop_scale@0.75"]),
        ("Rotation $75^{\\circ}$", ["rotate@75.0", "rotate@75"]), ("Mirror", ["mirror@0.0", "mirror@0"]),
        ("img2img + crop", ["combo_style_crop@1.0", "combo_style_crop@1"])]


def table(exp, method, name):
    p = RES / exp / "tables" / name
    if not p.exists():
        return None
    df = pd.read_csv(p)
    return df[df["method"] == method].set_index("cell")


def pick(df, cells, col):
    if df is None:
        return float("nan")
    for c in cells:
        if c in df.index:
            return float(df.loc[c, col])
    return float("nan")


SRC = {"ours21": table("final256_sd21", "stylering", "main_no_ecc.csv"), "gs21": table("final_gs256_sd21", "gaussian_shading", "main_soft.csv"),
       "ours15": table("final256", "stylering", "main_no_ecc.csv"), "gs15": table("final_gs256q", "gaussian_shading", "main_soft.csv")}
ID = json.load(open(RES / "ident_rows.json")) if (RES / "ident_rows.json").exists() else {"rows": {}, "avg": {}}
rows, avg = [], {k: {"tpr": [], "acc": []} for k in SRC}
for lab, cells in KEYS:
    v = {}
    for k, df in SRC.items():
        v[k] = (pick(df, cells, "tpr_1fpr"), pick(df, cells, "bit_acc_all"))
        if v[k][0] == v[k][0]:
            avg[k]["tpr"].append(v[k][0]); avg[k]["acc"].append(v[k][1])
    def cell(k, bold):
        t, a = v[k]
        s = "--" if t != t else f"{t:.2f}"
        return f"\\textbf{{{s}}}" if bold and t == t else s
    b21 = v["ours21"][0] >= v["gs21"][0] - 0.005 if v["ours21"][0] == v["ours21"][0] and v["gs21"][0] == v["gs21"][0] else False
    idr = ID["rows"].get(lab, {})
    def icell(m, key, bold):
        x = idr.get(m); x = x[key] if x else None
        return "--" if x is None else (f"\\textbf{{{x:.2f}}}" if bold else f"{x:.2f}")
    bi = (idr.get("ours") or {}).get("ident6", 0) >= (idr.get("gs") or {}).get("ident6", 0) - 0.005
    be = (idr.get("ours") or {}).get("e2e6", 0) >= (idr.get("gs") or {}).get("e2e6", 0) - 0.005
    rows.append(f"{lab} & {icell('ours', 'ident6', bi)} & {icell('gs', 'ident6', not bi)} & {icell('ours', 'e2e6', be)} & {icell('gs', 'e2e6', not be)} & {cell('ours21', b21)} & {cell('gs21', not b21)}\\\\")
m = {k: (float(np.mean(a["tpr"])) if a["tpr"] else float("nan"), float(np.mean(a["acc"])) if a["acc"] else float("nan")) for k, a in avg.items()}
ia = ID.get("avg", {})
rows.append("\\midrule\nAverage & " + " & ".join(f"{ia[m][key]:.2f}" if m in ia else "--" for key in ("ident6", "e2e6") for m in ("ours", "gs")) + " & " + " & ".join("--" if m[k][0] != m[k][0] else f"{m[k][0]:.2f}" for k in ("ours21", "gs21")) + "\\\\")
body = r"""\begin{table}[t]
\centering
\caption{Identification among $10^{6}$ enrolled users with random 256-bit identifiers on SD1.5 (Top-1 accuracy over all attacked images, an analytic estimate from the Hamming distance verified by Monte Carlo in Sec.~\ref{sec:exp-capacity}, and detected at 1\%~FPR with the true user ranked first), and TPR@1\%FPR on Stable Diffusion 2.1-base (thresholds from $1{,}000$ unwatermarked SD2.1 images). Best in bold.}
\label{tab:extra}
\setlength{\tabcolsep}{3pt}
\begin{tabular}{lcccccc}
\toprule
 & \multicolumn{2}{c}{Top-1, $10^{6}$} & \multicolumn{2}{c}{Detected $\wedge$ Top-1} & \multicolumn{2}{c}{SD2.1-base}\\
\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(lr){6-7}
Attack & \textbf{\method} & GS & \textbf{\method} & GS & \textbf{\method} & GS\\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{table}
"""
(OUT / "tab_extra.tex").write_text("% generated by code/notebooks/tab_sd21.py (identification rows from stats_extra.py) -- do not edit\n" + body)
lines = ["% generated by code/notebooks/tab_sd21.py -- do not edit"]
for k, tag in (("ours21", "SdOurs"), ("gs21", "SdGS"), ("ours15", "SdRefOurs"), ("gs15", "SdRefGS")):
    lines.append(f"\\newcommand{{\\n{tag}AvgTpr}}{{{m[k][0]:.2f}}}")
    lines.append(f"\\newcommand{{\\n{tag}AvgAcc}}{{{m[k][1]:.3f}}}")
(OUT / "numbers_sd21.tex").write_text("\n".join(lines) + "\n")
print("\n".join(rows)); print(m)
