# %% [markdown]
# # Supplementary table: compound-attack matrix (regeneration strength x geometric strength), SpecShade-256, unified detector
# Reads results/cmat256/tables/main_no_ecc.csv and the detection metadata (joint-search trigger and acceptance rates).
# Writes $TAB_OUT/tab_cmat.tex and $TAB_OUT/numbers_cmat.tex.   Usage: TAB_OUT=... python notebooks/tab_cmat.py
import json, os
from pathlib import Path
import numpy as np, pandas as pd
ROOT = Path(__file__).resolve().parents[1]; RES = ROOT / "results"
OUT = Path(os.environ.get("TAB_OUT", ROOT.parent / "docs" / "manuscripts" / "tables")); OUT.mkdir(parents=True, exist_ok=True)
df = pd.read_csv(RES / "cmat256" / "tables" / "main_no_ecc.csv"); df = df[df["method"] == "stylering"].set_index("cell")
rows = [json.loads(l) for l in open(RES / "cmat256" / "stylering" / "detect_no_ecc.jsonl")]
REG = [("regen1", "Regen.\\ $\\times1$"), ("img03", "img2img $s{=}0.3$"), ("img05", "img2img $s{=}0.5$")]
GEO = [("rot15", "Rot.\\ $15^{\\circ}$"), ("rot30", "Rot.\\ $30^{\\circ}$"), ("rot75", "Rot.\\ $75^{\\circ}$"), ("crop90", "Crop $0.9$"), ("crop75", "Crop $0.75$"), ("crop50", "Crop $0.5$")]
def cell(r, g):
    for k in (f"cm_{r}_{g}@1", f"cm_{r}_{g}@1.0"):
        if k in df.index: return float(df.loc[k, "tpr_1fpr"]), float(df.loc[k, "bit_acc_all"])
    return float("nan"), float("nan")
def rates(r, g):
    R = [x.get("meta") or {} for x in rows if x["attack"] == f"cm_{r}_{g}"]
    trig = np.mean([bool(m.get("geo_fallback")) for m in R]) if R else float("nan")
    acc = np.mean([bool(m.get("geo_fallback")) and not m.get("geo_gated", True) for m in R]) if R else float("nan")
    return trig, acc
lines, allt, trig_all, acc_all = [], [], [], []
for r, rl in REG:
    vals = []
    for g, gl in GEO:
        tpr, acc = cell(r, g); tr, ac = rates(r, g); allt.append(tpr); trig_all.append(tr); acc_all.append(ac)
        vals.append(f"{tpr:.2f} / {acc:.2f}")
    lines.append(rl + " & " + " & ".join(vals) + "\\\\")
body = r"""\begin{table*}[t]
\centering
\caption{Compound attacks of \method-256: a regeneration or style-transfer attack followed by a geometric edit (TPR@1\%FPR / bit accuracy, 100 images per cell, unified detector with the threshold of the paper). The joint search is triggered on """ + f"{100*np.nanmean(trig_all):.0f}" + r"""\% of the images and its peak passes the gate on """ + f"{100*np.nanmean(acc_all):.0f}" + r"""\%.}
\label{tab:cmat}
\setlength{\tabcolsep}{5pt}
\begin{tabular}{lcccccc}
\toprule
 & """ + " & ".join(gl for _, gl in GEO) + r"""\\
\midrule
""" + "\n".join(lines) + r"""
\bottomrule
\end{tabular}
\end{table*}
"""
(OUT / "tab_cmat.tex").write_text("% generated by code/notebooks/tab_cmat.py -- do not edit\n" + body)
(OUT / "numbers_cmat.tex").write_text("% generated by code/notebooks/tab_cmat.py -- do not edit\n" + "\n".join([
    f"\\newcommand{{\\nCmMaxTpr}}{{{np.nanmax(allt):.2f}}}", f"\\newcommand{{\\nCmTrig}}{{{100*np.nanmean(trig_all):.0f}}}",
    f"\\newcommand{{\\nCmAccept}}{{{100*np.nanmean(acc_all):.0f}}}", f"\\newcommand{{\\nCmRegenRotFifteen}}{{{cell('regen1','rot15')[0]:.2f}}}",
    f"\\newcommand{{\\nCmRegenCropNine}}{{{cell('regen1','crop90')[0]:.2f}}}", f"\\newcommand{{\\nCmImgThreeCropNine}}{{{cell('img03','crop90')[0]:.2f}}}"]) + "\n")
print("\n".join(lines)); print("max TPR", np.nanmax(allt), "trigger", np.nanmean(trig_all), "accept", np.nanmean(acc_all))
