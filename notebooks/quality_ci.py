# %% [markdown]
# # Image quality with uncertainty (GPU, ~5 min): FID / KID of the 1,000-image quality sets against COCO val2017 (5,000 images)
# Inception features are extracted once (clean-fid, mode "clean"); the FID is bootstrapped over the prompts. The methods share
# prompts and seeds, so the resampling is paired and also gives an interval for the FID difference to unwatermarked generation.
# KID: unbiased MMD^2 with the cubic polynomial kernel over 100 subsets of 1,000 features (clean-fid convention), mean +- std.
# Writes $TAB_OUT/numbers_quality.tex. Usage (GPU node): TAB_OUT=/path/to/paper/tables python notebooks/quality_ci.py

# %%
import json
import os
from pathlib import Path

import numpy as np
import torch

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
OUT = Path(os.environ.get("TAB_OUT", ROOT.parent / "docs" / "manuscripts" / "tables"))
OUT.mkdir(parents=True, exist_ok=True)
SETS = {"none": RES / "finalq/none/gen", "ours": RES / "finalq_fr256/stylering/gen", "gs": RES / "finalq/gaussian_shading/gen",
        "gm": RES / "finalq/gaussmarker/gen"}
REF = ROOT / "data/coco_fid/val2017"
RNG = np.random.default_rng(0)
N_BOOT = 1000

from cleanfid import fid as cf                      # noqa: E402
from cleanfid.features import build_feature_extractor  # noqa: E402

dev = "cuda" if torch.cuda.is_available() else "cpu"
model = build_feature_extractor("clean", dev)


CACHE = RES / "quality_feats"; CACHE.mkdir(exist_ok=True)


def feats(d):
    c = CACHE / (str(d).replace("/", "_").strip("_") + ".npy")
    if c.exists():
        return np.load(c)
    f = cf.get_folder_features(str(d), model=model, num_workers=8, batch_size=50, device=torch.device(dev), mode="clean", verbose=False)
    np.save(c, f); return f


LA = torch.device(dev)


def _t(x):
    return torch.as_tensor(np.asarray(x, dtype=np.float64), device=LA)


def _psd_sqrt(S):
    S = _t(S); S = (S + S.T) / 2
    w, v = torch.linalg.eigh(S)
    return (v * torch.sqrt(torch.clamp(w, min=0))) @ v.T


def fid_of(f, mu_r, sig_r, sqrt_r=None):
    """Frechet distance with tr sqrt(S_f S_r) = sum sqrt(eig(A A^T / (n-1))), A = X_c R, where X_c are the centred features
    (n x d) and R = S_r^{1/2}; the n x n eigenproblem replaces sqrtm on d x d matrices and gives the same value."""
    f = _t(f); n = f.shape[0]; mu = f.mean(0); Xc = f - mu
    R = _psd_sqrt(sig_r) if sqrt_r is None else sqrt_r
    A = Xc @ R
    G = A @ A.T / (n - 1)
    tr_sqrt = torch.sqrt(torch.clamp(torch.linalg.eigvalsh((G + G.T) / 2), min=0)).sum()
    tr_f = (Xc * Xc).sum() / (n - 1)
    mu_r_t, sig_r_t = _t(mu_r), _t(sig_r)
    return float(((mu - mu_r_t) ** 2).sum() + tr_f + torch.trace(sig_r_t) - 2 * tr_sqrt)


def kid_subsets(f, r, n_sub=50, m=1000):
    """Per-subset unbiased MMD^2 with k(x, y) = (x.y / d + 1)^3 (the clean-fid / Binkowski et al. estimator)."""
    d = f.shape[1]; m = min(m, len(f), len(r)); out = []
    ft, rt = _t(f), _t(r)
    for _ in range(n_sub):
        x = ft[torch.as_tensor(RNG.choice(len(f), m, replace=False), device=LA)]; y = rt[torch.as_tensor(RNG.choice(len(r), m, replace=False), device=LA)]
        a = (x @ x.T / d + 1) ** 3; b = (y @ y.T / d + 1) ** 3; c = (x @ y.T / d + 1) ** 3
        out.append(float((a.sum() - torch.diag(a).sum() + b.sum() - torch.diag(b).sum()) / (m * (m - 1)) - 2 * c.sum() / (m * m)))
    return np.asarray(out)


ref = feats(REF); mu_r, sig_r = np.mean(ref, axis=0), np.cov(ref, rowvar=False)
sqrt_r = _psd_sqrt(sig_r)
print('features ready', flush=True)
F = {k: feats(d) for k, d in SETS.items() if d.exists()}
n = min(len(f) for f in F.values())
print({k: len(f) for k, f in F.items()})
res = {}
for k, f in F.items():
    res[k] = {"fid": fid_of(f[:n], mu_r, sig_r, sqrt_r), "kid": kid_subsets(f[:n], ref)}
boot = {k: [] for k in F}
for b in range(N_BOOT):                              # paired bootstrap over the prompt indices
    idx = RNG.integers(0, n, n)
    for k, f in F.items():
        boot[k].append(fid_of(f[:n][idx], mu_r, sig_r, sqrt_r))
boot = {k: np.asarray(v) for k, v in boot.items()}
lines = ["% generated by code/notebooks/quality_ci.py -- do not edit"]
summary = {}
for k in F:
    lo, hi = np.quantile(boot[k], [0.025, 0.975])
    summary[k] = {"fid": res[k]["fid"], "fid_ci": [float(lo), float(hi)], "kid_x1e3": float(res[k]["kid"].mean() * 1e3), "kid_sd_x1e3": float(res[k]["kid"].std() * 1e3)}
    tag = {"none": "None", "ours": "Ours", "gs": "GS", "gm": "GM"}[k]
    lines += [f"\\newcommand{{\\nQFid{tag}}}{{{res[k]['fid']:.2f}}}", f"\\newcommand{{\\nQFid{tag}Lo}}{{{lo:.1f}}}", f"\\newcommand{{\\nQFid{tag}Hi}}{{{hi:.1f}}}",
              f"\\newcommand{{\\nKid{tag}}}{{{res[k]['kid'].mean() * 1e3:.1f}}}", f"\\newcommand{{\\nKid{tag}Sd}}{{{res[k]['kid'].std() * 1e3:.1f}}}"]
for k, tag in (("ours", "Ours"), ("gs", "GS"), ("gm", "GM")):
    if k in F:
        dlo, dhi = np.quantile(boot[k] - boot["none"], [0.025, 0.975])
        summary[k]["fid_diff_ci"] = [float(dlo), float(dhi)]
        lines += [f"\\newcommand{{\\nQFidDiff{tag}Lo}}{{{dlo:+.1f}}}", f"\\newcommand{{\\nQFidDiff{tag}Hi}}{{{dhi:+.1f}}}"]
lines.append(f"\\newcommand{{\\nQFidBootN}}{{{N_BOOT:,}}}".replace(",", "{,}"))
(OUT / "numbers_quality.tex").write_text("\n".join(lines) + "\n")
(RES / "quality_ci.json").write_text(json.dumps(summary, indent=1))
print(json.dumps(summary, indent=1))
