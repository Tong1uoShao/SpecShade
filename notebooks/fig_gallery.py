# %% [markdown]
# # Qualitative figures -- generated images of every method, and one image under every attack (GPU node, no GPU needed)
# Writes JPEG tiles to $FIG_OUT/gallery/ and two LaTeX figure* snippets to $TAB_OUT/{fig_gallery,fig_attacks}.tex
# (labels and TPRs are LaTeX text, so the tiles stay small and the fonts match the paper).
# Usage: FIG_OUT=$FIG_OUT TAB_OUT=$TAB_OUT \
#        GALLERY_PIDS=p0015,p0026,p0039,p0045 ATTACK_PID=p0014 python notebooks/fig_gallery.py

# %%
import os
from pathlib import Path

import pandas as pd
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
FIG = Path(os.environ.get("FIG_OUT", ROOT.parent / "docs" / "manuscripts" / "figs"))
TAB = Path(os.environ.get("TAB_OUT", ROOT.parent / "docs" / "manuscripts" / "tables"))
TILES = FIG / "gallery"
TILES.mkdir(parents=True, exist_ok=True)
PIDS = os.environ.get("GALLERY_PIDS", "p0015,p0026,p0039,p0045").split(",")
APID = os.environ.get("ATTACK_PID", "p0014")
SEED = 97
PX = 320
HEAD = "% generated by code/notebooks/fig_gallery.py -- do not edit\n"


def tile(src: Path, name: str) -> str:
    Image.open(src).convert("RGB").resize((PX, PX), Image.LANCZOS).save(TILES / f"{name}.jpg", quality=88)
    return f"figs/gallery/{name}.jpg"


# %% [markdown]
# ## Generated images: same prompt and seed, one column per method

# %%
METHODS = [("No watermark", "final/none"), ("Stable Sig.", "final/stable_signature"), ("VINE-R", "final/vine"),
           ("RingID", "final/ringid"), ("GS-256", "final_gs256/gaussian_shading"),
           ("GaussMarker-256", "gm256/gaussmarker_full"), ("\\textbf{\\method-256}", "final_fr256/stylering")]
w = 0.136
rows = [" & ".join(lab for lab, _ in METHODS) + " \\\\"]
for pid in PIDS:
    cells = [f"\\includegraphics[width={w}\\textwidth]{{{tile(RES / d / 'gen' / f'{pid}.png', f'gen_{pid}_{k}')}}}"
             for k, (_, d) in enumerate(METHODS)]
    rows.append(" & ".join(cells) + " \\\\")
(TAB / "fig_gallery.tex").write_text(HEAD + r"""\begin{figure*}[t]
\centering\footnotesize
\setlength{\tabcolsep}{1pt}\renewcommand{\arraystretch}{0.6}
\begin{tabular}{*{7}{c}}
""" + "\n".join(rows) + r"""
\end{tabular}
\caption{Images generated from the same prompts (rows) and seeds by all methods (columns). Semantic watermarks change the initial noise, so their images differ in content but not in quality from unwatermarked ones (Table~\ref{tab:quality}).}
\label{fig:gallery}
\end{figure*}
""")


# %% [markdown]
# ## One SpecShade-256 image under every attack, with the TPR of the attack cell

# %%
def tables():
    out = []
    for exp in ("final256", "geo256", "combo256"):
        p = RES / exp / "tables" / "main_no_ecc.csv"
        if p.exists():
            df = pd.read_csv(p)
            out.append(df[df["method"] == "stylering"])
    return out


TABS = tables()


def tpr(attack: str, s: float):
    for df in TABS:
        for cell, v in zip(df["cell"], df["tpr_1fpr"]):
            a, _, st = cell.rpartition("@")
            if a == attack and abs(float(st) - s) < 1e-6:
                return v
    return None


def attacked(attack: str, s: float) -> Path | None:
    for exp in ("combo256", "geo256", "final_fr256"):
        for f in sorted((RES / exp / "stylering" / "atk").glob(f"{APID}__{attack}_*_{SEED}.png")):
            a, _, st = f.name[len(APID) + 2:-len(f"_{SEED}.png")].rpartition("_")
            if a == attack and abs(float(st) - s) < 1e-6:
                return f
    return None


GRID = [
    [(None, None, "Watermarked"), ("regen_sd", 1, "Regen.\\ $\\times1$"), ("regen_sd", 2, "Regen.\\ $\\times2$"),
     ("regen_sd", 4, "Regen.\\ $\\times4$"), ("vae_cheng", 3, "VAE-Cheng"), ("vae_bmshj", 3, "VAE-Ball\\'e"),
     ("jpeg", 25, "JPEG $Q{=}25$"), ("median", 7, "Median $7$")],
    [("img2img_anime", 0.3, "img2img $s{=}0.3$"), ("img2img_anime", 0.5, "img2img $s{=}0.5$"),
     ("img2img_anime", 0.7, "img2img $s{=}0.7$"), ("ip2p_anime", 2.0, "IP2P $g_I{=}2.0$"), ("ip2p_anime", 1.0, "IP2P $g_I{=}1.0$"),
     ("adain_anime", 0.3, "AdaIN $\\alpha{=}0.3$"), ("adain_anime", 0.6, "AdaIN $\\alpha{=}0.6$"), ("adain_anime", 1.0, "AdaIN $\\alpha{=}1.0$")],
    [("noise", 0.1, "Noise $\\sigma{=}0.1$"), ("blur", 8, "Blur $r{=}8$"), ("resize", 0.25, "Resize $0.25$"),
     ("brightness", 6, "Brightness $\\times6$"), ("rand_drop", 0.8, "Pixel drop $80\\%$"), ("crop_scale", 0.75, "Crop $a{=}0.75$"),
     ("crop_scale", 0.5, "Crop $a{=}0.5$"), ("rotate", 30, "Rotation $30^{\\circ}$")],
    [("rotate", 75, "Rotation $75^{\\circ}$"), ("rotate", 90, "Rotation $90^{\\circ}$"), ("mirror", 0, "Mirror"),
     ("mirror", 1, "Vertical flip"), ("combo_crop_rotate", 1, "Crop + rotation"),
     ("combo_style_mirror", 1, "IP2P + mirror"), ("combo_style_crop", 1, "img2img + crop"), ("combo_regen_rotate", 1, "Regen.\\ + rotation")],
]
w = 0.119
rows, missing = [], []
for r, line in enumerate(GRID):
    ims, labs, nums = [], [], []
    for c, (a, s, lab) in enumerate(line):
        src = RES / "final_fr256" / "stylering" / "gen" / f"{APID}.png" if a is None else attacked(a, s)
        if src is None:
            missing.append(f"{a}@{s}")
            ims.append(""); labs.append(lab); nums.append("--")
            continue
        ims.append(f"\\includegraphics[width={w}\\textwidth]{{{tile(src, f'atk_{APID}_{r}{c}')}}}")
        labs.append(lab)
        v = None if a is None else tpr(a, float(s))
        nums.append("TPR" if a is None else ("--" if v is None else f"{v:.2f}"))
    rows += [" & ".join(ims) + " \\\\", " & ".join(labs) + " \\\\", " & ".join(nums) + " \\\\[3pt]"]
(TAB / "fig_attacks.tex").write_text(HEAD + r"""\begin{figure*}[t]
\centering\scriptsize
\setlength{\tabcolsep}{1pt}\renewcommand{\arraystretch}{0.85}
\begin{tabular}{*{8}{c}}
""" + "\n".join(rows) + r"""
\end{tabular}
\caption{One \method-256 image under the attacks of the evaluation. Below each image: the TPR@1\%FPR of \method-256 on that attack.}
\label{fig:attacks}
\end{figure*}
""")
print("tiles:", len(list(TILES.glob("*.jpg"))), "missing:", missing)
