# %% [markdown]
# # Qualitative figures -- generated images of every method, and one image under every attack (GPU node, no GPU needed)
# Writes JPEG tiles to $FIG_OUT/gallery/ and two LaTeX figure* snippets to $TAB_OUT/{fig_gallery,fig_attacks}.tex
# (labels and TPRs are LaTeX text, so the tiles stay small and the fonts match the paper).
# Usage: FIG_OUT=$FIG_OUT TAB_OUT=$TAB_OUT \
#        GALLERY_PIDS=p0015,p0026,p0039 ATTACK_PID=p0014 python notebooks/fig_gallery.py

# %%
import os
from pathlib import Path

import pandas as pd
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
FIG = Path(os.environ.get("FIG_OUT", ROOT.parent / "docs" / "manuscripts" / "figs"))
TAB = Path(os.environ.get("TAB_OUT", ROOT.parent / "docs" / "manuscripts" / "tables"))
TILES = FIG / "gallery"
TILES.mkdir(parents=True, exist_ok=True)
PIDS = os.environ.get("GALLERY_PIDS", "p0015,p0026,p0039").split(",")
APID = os.environ.get("ATTACK_PID", "p0014")
SEED = 97
PX = 320
HEAD = "% generated by code/notebooks/fig_gallery.py -- do not edit\n"


def tile(src: Path, name: str, px: int = PX) -> str:
    Image.open(src).convert("RGB").resize((px, px), Image.LANCZOS).save(TILES / f"{name}.jpg", quality=88)
    return f"figs/gallery/{name}.jpg"


# %% [markdown]
# ## Generated images: same prompt and seed, one column per method (main paper, Sec. IV-E)

# %%
METHODS = [("No watermark", "final/none"), ("Stable Sig.", "final/stable_signature"), ("VINE-R", "final/vine"),
           ("RingID", "final/ringid"), ("GS", "final_gs256/gaussian_shading"), ("GaussMarker", "gm256/gaussmarker_full"),
           ("SFW", "final_sfw/sfw_hsqr"), ("MaXsive", "final_maxsive/maxsive"), ("T2SMark", "final_t2s/t2smark"),
           ("\\textbf{\\method}", "final_fr256/stylering")]
w = 0.094      # tile width (fraction of \textwidth): ten columns fill the text width
rows = [" & ".join(f"{{\\scriptsize {lab}}}" for lab, _ in METHODS) + " \\\\[1pt]"]
for pid in PIDS:
    cells = [f"\\includegraphics[width={w}\\textwidth]{{{tile(RES / d / 'gen' / f'{pid}.png', f'gen_{pid}_{k}', px=256)}}}"
             for k, (_, d) in enumerate(METHODS)]
    rows.append(" & ".join(cells) + " \\\\")
(TAB / "fig_gallery.tex").write_text(HEAD + r"""\begin{figure*}[t]
\centering\footnotesize
\setlength{\tabcolsep}{1pt}\renewcommand{\arraystretch}{0.6}
\begin{tabular}{*{""" + str(len(METHODS)) + r"""}{c}}
""" + "\n".join(rows) + r"""
\end{tabular}
\caption{Images generated by all compared methods from the same prompts and seeds. Each row is one prompt and each column is one method, in the configuration of Section~\ref{sec:exp-setup}. Stable Signature and VINE-R keep the content of the unwatermarked image. The semantic watermarks change the initial noise, so their images differ in content but not in quality.}
\label{fig:gallery}
\end{figure*}
""")


# %% [markdown]
# ## One SpecShade-256 image under every attack, with the TPR of the attack cell

# %%
def tables():
    out = []
    for exp in ("final256", "geo256", "combo256"):
        p = RES / exp / "tables" / "main_no_ecc.csv"
        if p.exists():
            df = pd.read_csv(p)
            out.append(df[df["method"] == "stylering"])
    return out


TABS = tables()


def tpr(attack: str, s: float):
    for df in TABS:
        for cell, v in zip(df["cell"], df["tpr_1fpr"]):
            a, _, st = cell.rpartition("@")
            if a == attack and abs(float(st) - s) < 1e-6:
                return v
    return None


def attacked(attack: str, s: float) -> Path | None:
    for exp in ("combo256", "geo256", "final_fr256"):
        for f in sorted((RES / exp / "stylering" / "atk").glob(f"{APID}__{attack}_*_{SEED}.png")):
            a, _, st = f.name[len(APID) + 2:-len(f"_{SEED}.png")].rpartition("_")
            if a == attack and abs(float(st) - s) < 1e-6:
                return f
    return None


GRID = [   # two rows of eight: one setting per attack family that the text discusses (the full matrix is in the tables)
    [(None, None, "Watermarked"), ("regen_sd", 2, "Regen.\\ $\\times2$"), ("regen_sd", 4, "Regen.\\ $\\times4$"),
     ("img2img_anime", 0.5, "img2img $s{=}0.5$"), ("ip2p_anime", 1.0, "IP2P $g_I{=}1.0$"), ("adain_anime", 1.0, "AdaIN $\\alpha{=}1.0$"),
     ("jpeg", 25, "JPEG quality 25"), ("blur", 8, "Blur radius 8")],
    [("brightness", 6, "Brightness $\\times6$"), ("rand_drop", 0.8, "Pixel drop $80\\%$"), ("crop_scale", 0.5, "Crop $a{=}0.5$"),
     ("rotate", 75, "Rotation $75^{\\circ}$"), ("mirror", 0, "Mirror"), ("combo_crop_rotate", 1, "Crop + rotation"),
     ("combo_style_crop", 1, "img2img + crop"), ("combo_regen_rotate", 1, "Regen.\\ + rotation")],
]
w = 0.118      # tile width of the attack examples (two rows of eight fill the text width)
rows, missing = [], []
for r, line in enumerate(GRID):
    ims, labs, nums = [], [], []
    for c, (a, s, lab) in enumerate(line):
        src = RES / "final_fr256" / "stylering" / "gen" / f"{APID}.png" if a is None else attacked(a, s)
        if src is None:
            missing.append(f"{a}@{s}")
            ims.append(""); labs.append(lab); nums.append("--")
            continue
        ims.append(f"\\includegraphics[width={w}\\textwidth]{{{tile(src, f'atk_{APID}_{r}{c}')}}}")
        labs.append(lab)
        v = None if a is None else tpr(a, float(s))
        nums.append("TPR" if a is None else ("--" if v is None else f"{v:.2f}"))
    rows += [" & ".join(ims) + " \\\\", " & ".join(labs) + " \\\\", " & ".join(nums) + " \\\\[3pt]"]
(TAB / "fig_attacks.tex").write_text(HEAD + r"""\begin{figure*}[t]
\centering\footnotesize
\setlength{\tabcolsep}{1.5pt}\renewcommand{\arraystretch}{0.9}
\begin{tabular}{*{8}{c}}
""" + "\n".join(rows) + r"""
\end{tabular}
\caption{One \method-256 image under the attacks of the evaluation. Below each image: the TPR@1\%FPR of \method-256 on that attack.}
\label{fig:attacks}
\end{figure*}
""")
print("tiles:", len(list(TILES.glob("*.jpg"))), "missing:", missing)
