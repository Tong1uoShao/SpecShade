# %% [markdown]
# # Table: ablation of the synchronization (CPU only)
# The final detector with one component removed, on 50 prompts x 2 seeds of the existing attack sets (geo256, combo256).
# Rows = detector variants, columns = attacks, entries = TPR@1%FPR (bit accuracy). The full detector is evaluated on the
# same images. Writes $TAB_OUT/tab_syncabl.tex.
# Usage (GPU node): TAB_OUT=$TAB_OUT python notebooks/tab_syncabl.py

# %%
import json
import os
import re
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
OUT = Path(os.environ.get("TAB_OUT", ROOT.parent / "docs" / "manuscripts" / "tables"))
N_PROMPTS = 50
FILE = "detect_no_ecc.jsonl"; NULL = "detect_null_no_ecc.jsonl"


def jsonl(p):
    return [json.loads(l) for l in open(p)] if Path(p).exists() else []


def sc(x):
    return -np.inf if (x is None or not np.isfinite(x)) else float(x)


def cell_stats(exp, attack, strength, null_exp=None):
    rows = [r for r in jsonl(RES / exp / "stylering" / FILE) if r.get("kind") != "clean" and r["attack"] == attack
            and abs(float(r["strength"]) - strength) < 1e-6 and int(re.search(r"/p(\d+)__", r["image"]).group(1)) < N_PROMPTS]
    neg = np.asarray([sc(r["score"]) for r in jsonl(RES / (null_exp or exp) / "stylering" / NULL)], float)
    if not rows or not len(neg):
        return None
    thr = np.quantile(neg, 0.99, method="higher")
    return float((np.asarray([sc(r["score"]) for r in rows]) > thr).mean()), float(np.mean([r["bit_acc"] if r["bit_acc"] is not None else 0.5 for r in rows])), len(rows), len(neg)


COLS = [("Rot.\\ $75^{\\circ}$", "rotate", 75.0), ("Crop $0.75$", "crop_scale", 0.75), ("Crop $0.5$", "crop_scale", 0.5),
        ("Mirror", "mirror", 0.0), ("Crop + rot.", "combo_crop_rotate", 1.0)]
# (label, experiment that holds the geometric cells, experiment that holds the compound cell)
VARIANTS = [("Full detector", "geo256", "combo256"),
            ("w/o rotation search", "abl_sync_norot", None),
            ("w/o shift/scale search", "abl_sync_nocrop", None),
            ("w/o flip candidate", "abl_sync_noflip", None),
            ("integer-pixel shifts", "abl_sync_intpx", None),
            ("w/o joint search", None, "abl_sync_nojoint")]
lines, raw = [], {}
for lab, e_geo, e_combo in VARIANTS:
    cells = []
    for cl, a, s in COLS:
        compound = a.startswith("combo")
        e = e_combo if compound else e_geo
        st = cell_stats(e, a, s) if e else None
        raw[(lab, cl)] = st
        cells.append("--" if st is None else f"{st[0]:.2f}")
    lines.append(f"{lab} & " + " & ".join(cells) + "\\\\")
hdr = " & ".join(["Detector"] + [c for c, _, _ in COLS]) + "\\\\"
body = r"""\begin{table}[t]
\centering
\caption{Ablation of the self-synchronization: TPR@1\%FPR of the 256-bit detector with one component removed, on 50 prompts $\times$ 2 attack seeds.}
\label{tab:syncabl}
\footnotesize
\setlength{\tabcolsep}{2pt}
\begin{tabular}{lccccc}
\toprule
""" + hdr + r"""
\midrule
""" + "\n".join(lines) + r"""
\bottomrule
\end{tabular}
\end{table}
"""
(OUT / "tab_syncabl.tex").write_text("% generated by code/notebooks/tab_syncabl.py -- do not edit\n" + body)
print("\n".join(lines))
print({k: (v[2], v[3]) for k, v in raw.items() if v})
